import { useState } from 'react';
import { ListChecks, Copy, Check, PhoneCall, ExternalLink, ShieldAlert, FileDown, ShieldCheck } from 'lucide-react';
import { playSuccess, playTick } from '../lib/audio';
import type { Verdict } from '../engine';
import { type Language, TRANSLATIONS } from '../lib/i18n';

interface VerifyLadderProps {
  verdict: Verdict;
  rawText: string;
  lang?: Language;
}

export const VerifyLadder = ({ verdict, rawText, lang = 'en' }: VerifyLadderProps) => {
  const [copied, setCopied] = useState(false);
  const [downloading, setDownloading] = useState(false);
  const t = TRANSLATIONS[lang];

  const getSha256 = async (str: string) => {
    try {
      const buffer = new TextEncoder().encode(str);
      const hashBuffer = await crypto.subtle.digest('SHA-256', buffer);
      return Array.from(new Uint8Array(hashBuffer))
        .map((b) => b.toString(16).padStart(2, '0'))
        .join('');
    } catch {
      return 'N/A';
    }
  };

  const generateEvidenceText = async () => {
    const timestampIST = new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' });
    const timestampUTC = new Date().toISOString();
    const shaHash = await getSha256(rawText);

    return `================================================================================
SECTION 65B EVIDENCE DOCKET (BHARATIYA SAKSHYA ADHINIYAM / INDIAN EVIDENCE ACT)
GENERATED BY PAUSEPOINT FORENSIC COGNITIVE FIREWALL — LOCAL CLIENT VERIFICATION
================================================================================

CERTIFICATE OF ELECTRONIC EVIDENCE INTEGRITY
1. Digital Record Hash (SHA-256):
   ${shaHash}

2. Acquisition Timestamps:
   • Indian Standard Time (IST): ${timestampIST}
   • Universal Coordinated Time (UTC): ${timestampUTC}

3. Forensic Evaluation Summary:
   • Threat Verdict: ${verdict.headline}
   • Composite Threat Score: ${verdict.score} / 100 (${verdict.level.toUpperCase()})
   • Processing Mode: 100% Client-Side Local Memory (Zero cloud transmission)

================================================================================
I. EXACT SUSPICIOUS RAW PAYLOAD RECEIVED BY CITIZEN:
--------------------------------------------------------------------------------
${rawText}

================================================================================
II. PSYCHOLOGICAL MANIPULATION & PRESSURE VECTORS IDENTIFIED:
--------------------------------------------------------------------------------
${verdict.tactics.length > 0
  ? verdict.tactics.map((t, i) => `${i + 1}. [${t.label.toUpperCase()}]
   • Psychological Lever: ${t.lever}
   • Extracted Trigger Words: ${t.examples.join(', ')}`).join('\n\n')
  : 'No distinct psychological pressure triggers recognized.'}

================================================================================
III. MATCHED KNOWN FRAUD PLAYBOOKS (MODUS OPERANDI):
--------------------------------------------------------------------------------
${verdict.playbooks.length > 0
  ? verdict.playbooks.map((p, i) => `${i + 1}. Pattern Name: ${p.name}
   • Core Disproof Fact: ${p.truth}`).join('\n\n')
  : 'No standardized playbook catalog match.'}

================================================================================
IV. LINK & TELECOM INFRASTRUCTURE DEEP INSPECTION:
--------------------------------------------------------------------------------
${verdict.links.length > 0
  ? verdict.links.map((l, i) => `${i + 1}. URL Inspected: ${l.url}
   • Real Registered Domain: ${l.domain}
   • Known Official Authority Domain: ${l.official ? 'VERIFIED (SAFE/LEGIT)' : 'NO (UNVERIFIED / DECEPTIVE)'}
   • Threat Risk Score: ${l.risk}/100 (${l.risk >= 40 ? 'HIGH RISK' : l.risk > 0 ? 'SUSPICIOUS' : 'MINIMAL RISK'})`).join('\n\n')
  : 'No embedded hyperlinks found.'}

================================================================================
V. APPLICABLE INDIAN LEGAL CONTEXT & OFFENSES:
--------------------------------------------------------------------------------
• Section 66D, Information Technology Act 2000 (Cheating by personation using computer resource)
• Section 420 / Section 318(4) Bharatiya Nyaya Sanhita (Cheating and dishonestly inducing delivery of property)
• Section 319 / Section 336 Bharatiya Nyaya Sanhita (Extortion / Criminal Intimidation where applicable)

================================================================================
VI. CITIZEN EMERGENCY INCIDENT PROTOCOL:
--------------------------------------------------------------------------------
1. Dial 1930 immediately if any banking or financial transfer occurred within the golden hour.
2. File formal complaint on https://cybercrime.gov.in and attach this electronic evidence docket.
3. Report the offending telecom sender/number on Sanchar Saathi Chakshu (https://sancharsaathi.gov.in).
4. Do NOT call back the suspect number or install any APK / remote access application.

Generated autonomously via PausePoint Cognitive Firewall.
Offline Evidence Verification ID: PP-${shaHash.slice(0, 12).toUpperCase()}
================================================================================`;
  };

  const copyReport = async () => {
    playTick();
    const docket = await generateEvidenceText();
    await navigator.clipboard.writeText(docket);
    setCopied(true);
    playSuccess();
    setTimeout(() => setCopied(false), 2500);
  };

  const downloadDocket = async () => {
    playTick();
    setDownloading(true);
    try {
      const docket = await generateEvidenceText();
      const blob = new Blob([docket], { type: 'text/plain;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `PausePoint-Evidence-Docket-${Date.now()}.txt`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
      playSuccess();
    } finally {
      setDownloading(false);
    }
  };

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: '0.85rem' }}>
      <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', flexWrap: 'wrap', gap: '0.5rem' }}>
        <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
          <ListChecks size={18} style={{ color: 'var(--color-brand)' }} />
          <h3 style={{ fontSize: '0.95rem', fontWeight: 700, textTransform: 'uppercase', letterSpacing: '0.04em' }}>
            {t.actionProtocolTitle}
          </h3>
        </div>

        <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem', flexWrap: 'wrap' }}>
          <button
            onClick={downloadDocket}
            disabled={downloading}
            style={{
              display: 'inline-flex',
              alignItems: 'center',
              gap: '0.4rem',
              padding: '0.4rem 0.85rem',
              borderRadius: 'var(--radius-pill)',
              border: '1px solid var(--color-border)',
              background: 'var(--color-surface-2)',
              color: 'var(--color-fg)',
              fontSize: '0.8rem',
              fontWeight: 600,
              cursor: 'pointer',
              transition: 'all 0.15s ease',
            }}
            title="Download Section 65B Electronic Evidence Docket file for Police & Cybercell reporting"
          >
            <FileDown size={14} color="var(--color-brand)" />
            <span>{lang === 'hi' ? 'सेक्शन 65B रिपोर्ट डाउनलोड करें' : 'Download Evidence Docket (.txt)'}</span>
          </button>

          <button
            onClick={copyReport}
            style={{
              display: 'inline-flex',
              alignItems: 'center',
              gap: '0.4rem',
              padding: '0.4rem 0.85rem',
              borderRadius: 'var(--radius-pill)',
              border: '1px solid var(--color-brand)',
              background: copied ? 'var(--color-success-bg)' : 'transparent',
              color: copied ? 'var(--color-success-fg)' : 'var(--color-brand)',
              fontSize: '0.8rem',
              fontWeight: 600,
              cursor: 'pointer',
              transition: 'all 0.15s ease',
            }}
          >
            {copied ? <Check size={14} /> : <Copy size={14} />}
            <span>{copied ? t.reportCopied : t.copyReportBtn}</span>
          </button>
        </div>
      </div>

      <div
        style={{
          display: 'flex',
          flexDirection: 'column',
          gap: '0.65rem',
          padding: '1.25rem',
          borderRadius: 'var(--radius-md)',
          background: 'var(--color-surface)',
          border: '1px solid var(--color-border)',
        }}
      >
        {verdict.verifySteps.map((step, idx) => (
          <div
            key={idx}
            style={{
              display: 'flex',
              alignItems: 'flex-start',
              gap: '0.75rem',
              fontSize: '0.92rem',
              color: 'var(--color-fg)',
              lineHeight: 1.5,
            }}
          >
            <div
              style={{
                width: 24,
                height: 24,
                borderRadius: '50%',
                background: 'var(--color-surface-2)',
                border: '1px solid var(--color-border)',
                color: 'var(--color-brand)',
                fontSize: '0.75rem',
                fontWeight: 700,
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'center',
                flexShrink: 0,
                marginTop: 1,
              }}
            >
              {idx + 1}
            </div>
            <div>{step}</div>
          </div>
        ))}

        {/* Section 65B Legal Badge */}
        <div
          style={{
            display: 'flex',
            alignItems: 'center',
            gap: '0.5rem',
            padding: '0.65rem 0.9rem',
            borderRadius: 'var(--radius-sm)',
            background: 'rgba(2, 132, 199, 0.06)',
            border: '1px solid rgba(2, 132, 199, 0.2)',
            fontSize: '0.76rem',
            color: 'var(--color-fg-muted)',
            marginTop: '0.35rem',
          }}
        >
          <ShieldCheck size={16} color="var(--color-brand)" style={{ flexShrink: 0 }} />
          <span>
            {lang === 'hi'
              ? 'भारतीय साक्ष्य अधिनियम की धारा 65B के अनुसार तैयार: यह डिजिटल डॉकेट कानूनी शिकायत दर्ज करने हेतु न्यायालय-मान्य है।'
              : 'Indian Evidence Act Section 65B / BSA Sec 63 Ready: Electronic evidence integrity hashed via SHA-256 for formal FIR & police reporting.'}
          </span>
        </div>

        {/* Quick Indian Reporting Portals Buttons */}
        <div
          style={{
            display: 'flex',
            alignItems: 'center',
            gap: '0.65rem',
            flexWrap: 'wrap',
            paddingTop: '0.85rem',
            marginTop: '0.5rem',
            borderTop: '1px solid var(--color-border-subtle)',
          }}
        >
          <a
            href="tel:1930"
            onClick={playTick}
            style={{
              display: 'inline-flex',
              alignItems: 'center',
              gap: '0.45rem',
              padding: '0.5rem 0.9rem',
              borderRadius: 'var(--radius-md)',
              background: 'var(--color-danger)',
              color: '#ffffff',
              fontSize: '0.84rem',
              fontWeight: 700,
              textDecoration: 'none',
              boxShadow: 'var(--shadow-sm)',
            }}
          >
            <PhoneCall size={15} />
            {t.dialHelpline}
          </a>

          <a
            href="https://cybercrime.gov.in"
            target="_blank"
            rel="noopener noreferrer"
            onClick={playTick}
            style={{
              display: 'inline-flex',
              alignItems: 'center',
              gap: '0.45rem',
              padding: '0.5rem 0.9rem',
              borderRadius: 'var(--radius-md)',
              background: 'var(--color-surface-2)',
              border: '1px solid var(--color-border)',
              color: 'var(--color-fg)',
              fontSize: '0.84rem',
              fontWeight: 600,
              textDecoration: 'none',
            }}
          >
            <ExternalLink size={14} />
            cybercrime.gov.in
          </a>

          <a
            href="https://sancharsaathi.gov.in/sfc/"
            target="_blank"
            rel="noopener noreferrer"
            onClick={playTick}
            style={{
              display: 'inline-flex',
              alignItems: 'center',
              gap: '0.45rem',
              padding: '0.5rem 0.9rem',
              borderRadius: 'var(--radius-md)',
              background: 'var(--color-surface-2)',
              border: '1px solid var(--color-border)',
              color: 'var(--color-fg)',
              fontSize: '0.84rem',
              fontWeight: 600,
              textDecoration: 'none',
            }}
          >
            <ShieldAlert size={14} />
            Sanchar Saathi (Chakshu)
          </a>
        </div>
      </div>
    </div>
  );
};
